#!/usr/bin/env python3
"""Write a synthetic build.ninja with the shape of a CMake-generated LLVM build.

    gen_manifest.py OUTDIR LIBS [SEED]

writes OUTDIR/build.ninja and OUTDIR/CMakeFiles/rules.ninja. LIBS is the number
of library targets; LLVM with clang, lld, mlir and clang-tools-extra has 782.
Per library, the mix follows results/shape-large.txt: about 11 compiles (1 source,
1 order-only phony, 10 bindings), 21 custom commands (tablegen-like: a tool, a
shared set of .td inputs, COMMAND/DESC/restat, some `${cmake_ninja_workdir}`
outputs), one static-library link (its objects, the libraries it depends on as
order-only), half an executable link, and about 37 phony statements. Same
seed, same bytes.
"""
import os
import random
import sys

AREAS = ["Support", "IR", "Analysis", "Transforms", "CodeGen", "MC", "Target",
         "Object", "Frontend", "Sema", "Parse", "AST", "Lex", "Driver", "Dialect",
         "Conversion", "Tooling", "ELF", "COFF", "Passes"]
SRC = "/src/llvm-project"
FLAGS = ("-O3 -DNDEBUG -std=c++17 -fPIC -fno-exceptions -funwind-tables -fno-rtti "
         "-fvisibility-inlines-hidden -Werror=date-time -Wall -Wextra -Wno-unused-parameter "
         "-Wwrite-strings -Wcast-qual -Wno-missing-field-initializers -pedantic "
         "-Wno-long-long -Wimplicit-fallthrough -Wno-maybe-uninitialized -Wno-noexcept-type "
         "-Wdelete-non-virtual-dtor -Wno-comment -Wno-misleading-indentation "
         "-fdiagnostics-color -ffunction-sections -fdata-sections")
DEFINES = ("-DGTEST_HAS_RTTI=0 -D_DEBUG -D_GLIBCXX_ASSERTIONS -D_GNU_SOURCE "
           "-D__STDC_CONSTANT_MACROS -D__STDC_FORMAT_MACROS -D__STDC_LIMIT_MACROS")


def main():
    out, nlibs = sys.argv[1], int(sys.argv[2])
    rng = random.Random(int(sys.argv[3]) if len(sys.argv) > 3 else 1)
    os.makedirs(os.path.join(out, "CMakeFiles"), exist_ok=True)
    rules = open(os.path.join(out, "CMakeFiles", "rules.ninja"), "w")
    b = open(os.path.join(out, "build.ninja"), "w")
    w = b.write

    rules.write("# CMAKE generated file: DO NOT EDIT!\n\nninja_required_version = 1.5\n\n"
                "rule CUSTOM_COMMAND\n  command = $COMMAND\n  description = $DESC\n\n")
    w("# CMAKE generated file: DO NOT EDIT!\n# Generated by \"Ninja\" Generator, CMake Version 4.4\n\n"
      "ninja_required_version = 1.8.2\n\nCONFIGURATION = Release\n"
      "cmake_ninja_workdir = /build/llvm/\n\ninclude CMakeFiles/rules.ninja\n\n")

    # A shared pool of .td files per area: custom commands draw their inputs from it.
    tds = {a: ["%s/llvm/include/llvm/%s/%s%d.td" % (SRC, a, a, k) for k in range(rng.randint(60, 180))]
           for a in AREAS}
    libs = []          # (name, archive path, order-depends phony)
    closures = {}      # archive path -> archives it links against
    allphony = []
    for i in range(nlibs):
        area = AREAS[i % len(AREAS)]
        name = "LLVM%s%d" % (area, i)
        sdir = "%s/llvm/lib/%s/%s" % (SRC, area, name)
        odir = "lib/%s/%s/CMakeFiles/%s.dir" % (area, name, name)
        order = "cmake_object_order_depends_target_%s" % name
        deps = rng.sample(libs, min(len(libs), rng.randint(0, 6)))
        # What it links against: its deps and theirs, at most 80 (LLVM: 54 on average).
        closure = sorted(set(d[1] for d in deps).union(*[closures[d[1]] for d in deps]))
        if len(closure) > 80:
            closure = sorted(rng.sample(closure, 80))
        cc_rule = "CXX_COMPILER__%s_unscanned_Release" % name
        ar_rule = "CXX_STATIC_LIBRARY_LINKER__%s_Release" % name
        rules.write("rule %s\n  depfile = $DEP_FILE\n  deps = gcc\n"
                    "  command = ${LAUNCHER}${CODE_CHECK}/usr/bin/c++ $DEFINES $INCLUDES $FLAGS "
                    "-MD -MT $out -MF $DEP_FILE -o $out -c $in\n"
                    "  description = Building CXX object $out\n\n" % cc_rule)
        rules.write("rule %s\n  command = $PRE_LINK && /usr/bin/cmake -E rm -f $TARGET_FILE && "
                    "/usr/bin/ar qc $TARGET_FILE $LINK_FLAGS $in && /usr/bin/ranlib $TARGET_FILE "
                    "&& $POST_BUILD\n  description = Linking CXX static library $TARGET_FILE\n"
                    "  restat = $RESTAT\n\n" % ar_rule)

        # Custom commands (tablegen and friends).
        gen = []
        tool = "bin/llvm-tblgen"
        for k in range(rng.randint(10, 32)):
            o = "include/llvm/%s/%s/Gen%d.inc" % (area, name, k)
            gen.append(o)
            ins = rng.sample(tds[area], min(len(tds[area]), rng.randint(40, 200)))
            extra = (" | ${cmake_ninja_workdir}%s" % o) if rng.random() < 0.4 else ""
            w("\n#############################################\n# Custom command for %s\n\n" % o)
            w("build %s%s: CUSTOM_COMMAND %s %s || %s\n" % (o, extra, tool, " ".join(ins), tool))
            w("  COMMAND = cd /build/llvm/lib/%s/%s && /build/llvm/%s -gen-%s -I %s/llvm/include "
              "-I %s %s/%s.td --write-if-changed -o /build/llvm/%s -d %s.d\n"
              % (area, name, tool, area.lower(), SRC, sdir, sdir, name, o, o))
            w("  DESC = Building %s...\n  restat = 1\n" % os.path.basename(o))

        # The order-depends phony: generated headers and the deps' phonies.
        w("\nbuild %s: phony || %s\n" % (order, " ".join(gen + [d[2] for d in deps])))

        # Compiles.
        objs = []
        for k in range(1 + int(rng.expovariate(1 / 10.0))):
            src = "%s/File%d.cpp" % (sdir, k)
            obj = "%s/File%d.cpp.o" % (odir, k)
            objs.append(obj)
            w("\nbuild %s: %s %s || %s\n" % (obj, cc_rule, src, order))
            w("  CONFIG = Release\n  DEFINES = %s\n  DEP_FILE = %s.d\n  FLAGS = %s\n"
              "  INCLUDES = -I/build/llvm/lib/%s/%s -I%s -I/build/llvm/include -I%s/llvm/include\n"
              "  OBJECT_DIR = %s\n  OBJECT_FILE_DIR = %s\n  TARGET_COMPILE_PDB = %s/\n"
              "  TARGET_PDB = lib/lib%s.pdb\n  TARGET_SUPPORT_DIR = %s\n"
              % (DEFINES, obj, FLAGS, area, name, sdir, SRC, odir, odir, odir, name, odir))

        # The archive.
        ar = "lib/lib%s.a" % name
        w("\nbuild %s: %s %s || %s\n" % (ar, ar_rule, " ".join(objs), " ".join(closure)))
        w("  CONFIG = Release\n  LANGUAGE_COMPILE_FLAGS = -O3 -DNDEBUG\n  OBJECT_DIR = %s\n"
          "  POST_BUILD = :\n  PRE_LINK = :\n  TARGET_COMPILE_PDB = %s/%s.pdb\n  TARGET_FILE = %s\n"
          "  TARGET_PDB = %s.pdb\n  TARGET_SUPPORT_DIR = %s\n" % (odir, odir, name, ar, ar, odir))

        # Sometimes a tool linked against this library and its deps.
        if rng.random() < 0.5:
            exe = "bin/%s-tool" % name.lower()
            rule = "CXX_EXECUTABLE_LINKER__%s-tool_Release" % name.lower()
            rules.write("rule %s\n  command = $PRE_LINK && /usr/bin/c++ $FLAGS $LINK_FLAGS $in -o "
                        "$TARGET_FILE $LINK_PATH $LINK_LIBRARIES && $POST_BUILD\n"
                        "  description = Linking CXX executable $TARGET_FILE\n  restat = $RESTAT\n\n"
                        % rule)
            libdeps = [ar] + closure
            w("\nbuild %s: %s %s | %s || %s\n" % (exe, rule, objs[0], " ".join(libdeps), " ".join(libdeps)))
            w("  CONFIG = Release\n  FLAGS = -O3 -DNDEBUG\n  LINK_FLAGS = -Wl,-rpath-link,/build/llvm/./lib"
              " -Wl,--gc-sections\n  LINK_LIBRARIES = %s -lrt -ldl -lm /usr/lib64/libz.so\n"
              "  OBJECT_DIR = %s\n  POST_BUILD = :\n  PRE_LINK = :\n  TARGET_COMPILE_PDB = %s/\n"
              "  TARGET_FILE = %s\n  TARGET_PDB = %s.pdb\n  TARGET_SUPPORT_DIR = %s\n"
              % (" ".join(libdeps), odir, odir, exe, exe, odir))
            w("\nbuild %s-tool: phony %s\n" % (name.lower(), exe))

        # Aliases and per-directory phonies, as CMake writes them.
        w("\nbuild %s: phony %s\n" % (name, ar))
        for k in range(rng.randint(20, 50)):
            p = "lib/%s/%s/CMakeFiles/phony%d.util" % (area, name, k)
            w("\nbuild %s: phony %s\n" % (p, " ".join(rng.sample(objs + gen, min(len(objs + gen), rng.randint(1, 20))))))
            allphony.append(p)
        libs.append((name, ar, order))
        closures[ar] = closure

    w("\nbuild all: phony %s\n\ndefault all\n" % " ".join(l[1] for l in libs))


if __name__ == "__main__":
    main()
